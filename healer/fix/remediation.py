"""Stage 3, Remediate: safe, reversible, auditable (Chapter 2).

Everything the fix stage does happens on a `healer/`-prefixed branch, never on the base
branch. Deleting a branch is a safe, cheap undo with zero blast radius.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from datetime import date
from typing import Any

from healer.fix.git_ops import GitError, GitOps
from healer.guardrails.allowlist import is_path_remediable

_DIFF_FILE = re.compile(r"^diff --git a/(\S+) b/(\S+)", re.MULTILINE)


def slugify(text: str, max_length: int = 40) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:max_length].strip("-")


_HEADER = re.compile(r"^(---|\+\+\+) (\S+)", re.MULTILINE)


def _strip_prefix(path: str) -> str:
    return path[2:] if path.startswith(("a/", "b/")) else path


def normalize_diff(diff: str) -> str:
    """Give a model-written diff the headers git expects.

    Found on real Bedrock: a model answers with bare `--- src/auth.py` / `+++ src/auth.py`
    and no `diff --git` line or `a/`, `b/` prefixes. `git apply` then strips `src/` and fails.
    Missing headers are added; a diff that already has them is returned untouched.
    """
    if _DIFF_FILE.search(diff):
        return diff
    out: list[str] = []
    lines = diff.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("--- ") and i + 1 < len(lines) and lines[i + 1].startswith("+++ "):
            old = _strip_prefix(line[4:].split("\t")[0].strip())
            new = _strip_prefix(lines[i + 1][4:].split("\t")[0].strip())
            name = new if new != "/dev/null" else old
            out += [f"diff --git a/{name} b/{name}", f"--- a/{old}", f"+++ b/{new}"]
            i += 2
            continue
        out.append(line)
        i += 1
    return "\n".join(out) + ("\n" if diff.endswith("\n") else "")


_SYMLINK_MODE = re.compile(r"^(?:new file mode|old mode|new mode|index \S+ )\s*120000", re.M)


def files_in_diff(diff: str) -> list[str]:
    """Every file path the diff actually touches (both the old and the new name).

    Reads the `---` and `+++` lines as well as `diff --git`, so a diff cannot hide a forbidden
    file by leaving out the `diff --git` header.
    """
    paths: list[str] = []
    candidates = [p for pair in _DIFF_FILE.findall(diff) for p in pair]
    candidates += [_strip_prefix(m[1]) for m in _HEADER.findall(diff)]
    for path in candidates:
        if path != "/dev/null" and path not in paths:
            paths.append(path)
    return paths


def diff_summary(diff: str) -> str:
    """A short label for the branch name, taken from the first file the diff touches."""
    paths = files_in_diff(diff)
    return f"fix {paths[0]}" if paths else "fix"


def apply_remediation(
    diff: str,
    changed_files: list[str],
    git: GitOps,
    base: str = "main",
    today: date | None = None,
    is_remediable: Callable[[str], bool] = is_path_remediable,
    suffix: str = "",
) -> dict[str, Any]:
    """Apply a model-written diff on a healer/ branch, or refuse and say why.

    `suffix` makes the branch name unique, as in the book's own example
    (`healer/2024-03-15-typeerror-cannot-read-prop-a1b2c3`): two incidents touching the same
    file on the same day must not collide.

    Hardening beyond the book's listing: the allowlist is checked against the files the diff
    actually touches, not only the list the model declared. A model that declares a safe file
    while the diff edits a workflow file must not get through.
    """
    diff = normalize_diff(diff)
    touched = files_in_diff(diff)
    if not touched:
        return {"applied": False, "reason": "the diff names no file, so it is not a patch"}
    undeclared = [f for f in touched if f not in changed_files]
    if undeclared:
        return {"applied": False, "reason": f"diff touches undeclared files: {undeclared}"}

    if _SYMLINK_MODE.search(diff):
        return {"applied": False, "reason": "diff creates or changes a symbolic link"}

    unsafe = [f for f in dict.fromkeys([*changed_files, *touched]) if not is_remediable(f)]
    if unsafe:
        return {"applied": False, "reason": f"forbidden paths: {unsafe}"}

    summary = diff_summary(diff)
    tail = f"-{suffix}" if suffix else ""
    branch = f"healer/{today or date.today()}-{slugify(summary)}{tail}"
    try:
        git.checkout_branch(branch, base=base)
    except GitError as exc:
        return {"applied": False, "reason": f"could not create the branch: {exc}"}
    result = git.apply_patch(diff)
    if not result.success:
        git.rollback_branch(branch, base=base)  # leave the base branch untouched on partial apply
        return {"applied": False, "reason": result.error}

    git.commit(f"fix(healer): {summary}\n\nAuto-generated by the self-healing pipeline.")
    git.push_branch(branch)
    return {"applied": True, "branch": branch, "rollback": lambda: git.delete_branch(branch)}
